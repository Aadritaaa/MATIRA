const i18n = {
    LANG_KEY: 'matira_lang',

    getLang() {
        return localStorage.getItem(this.LANG_KEY) || 'en';
    },

    setLang(lang) {
        if (['en', 'bn'].includes(lang)) {
            localStorage.setItem(this.LANG_KEY, lang);
            this.applyTranslations();
            // Dispatch event for UI updates
            window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
        }
    },

    t(key, fallback = '') {
        const lang = this.getLang();
        return I18N_DICTIONARY[lang]?.[key] || I18N_DICTIONARY['en']?.[key] || fallback || key;
    },

    /**
     * Scan DOM for data-i18n and data-i18n-placeholder attributes
     */
    applyTranslations() {
        const lang = this.getLang();
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (key) {
                el.textContent = this.t(key, el.textContent);
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (key) {
                el.placeholder = this.t(key, el.placeholder);
            }
        });

        // Update active class on language switcher buttons if any
        document.querySelectorAll('.lang-btn').forEach(btn => {
            const btnLang = btn.getAttribute('data-lang');
            if (btnLang === lang) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });
    },

    /**
     * Render standard language switcher markup in specified container
     */
    renderSelector(containerId = 'langSelectorContainer') {
        const container = document.getElementById(containerId);
        if (!container) return;

        const currentLang = this.getLang();
        container.innerHTML = `
            <div class="language-switcher">
                <span style="font-size: 0.85rem; color: var(--text-muted); font-weight: 500;">🌐 Language:</span>
                <button type="button" class="lang-btn ${currentLang === 'en' ? 'active' : ''}" data-lang="en">English</button>
                <span style="color: var(--border-color);">|</span>
                <button type="button" class="lang-btn ${currentLang === 'bn' ? 'active' : ''}" data-lang="bn">বাংলা</button>
            </div>
        `;

        container.querySelectorAll('.lang-btn').forEach(btn => {
            btn.addEventListener('click', (e) => {
                e.preventDefault();
                const selected = btn.getAttribute('data-lang');
                this.setLang(selected);
            });
        });
    },

    init() {
        this.renderSelector('langSelectorContainer');
        this.renderSelector('navLangContainer');
        this.applyTranslations();
    }
};

document.addEventListener('DOMContentLoaded', () => {
    i18n.init();
});
